#!/usr/bin/env python3
"""
convert_hnmod.py - Converts Horizon Native Mods (.hnmod/.hmod/.zip) into iOS arm64 dynamic libraries (.dylib)
with C-ABI v2 HorizonDylibModVTable + keybinds + horizon_mod_register() exports.
"""

import os
import re
import sys
import json
import zipfile
import tarfile
import shutil
import argparse
import subprocess
from pathlib import Path

try:
    import tomllib
except ImportError:
    tomllib = None

CARGO_TOML_TEMPLATE = """[package]
name = "{crate_name}"
version = "{cargo_version}"
edition = "2021"

[lib]
crate-type = ["cdylib"]
name = "{crate_name}"

[profile.release]
opt-level = 3
lto = true
codegen-units = 1
panic = "abort"
strip = true
"""

RUST_BRIDGE_TEMPLATE = """// Generated by hnmod-dylib-builder for Metallic Horizon iOS Runtime
// Target: aarch64-apple-ios (ABI v2)

use std::ffi::c_void;
use std::os::raw::{{c_char, c_int}};
use std::sync::atomic::{{AtomicBool, Ordering}};
use std::sync::Mutex;

pub const HORIZON_DYLIB_ABI_VERSION: u32 = 2;

#[repr(C)]
pub struct HorizonHostContext {{
    pub abi_version: u32,
    pub user_data: *mut c_void,
    pub is_playing: extern "C" fn() -> u8,
    pub is_key_down: extern "C" fn(mod_id: *const c_char, key_id: *const c_char) -> u8,
    pub get_setting_f64: extern "C" fn(mod_id: *const c_char, key: *const c_char, default_val: f64) -> f64,
    pub get_setting_bool: extern "C" fn(mod_id: *const c_char, key: *const c_char, default_val: u8) -> u8,
}}

#[repr(C)]
pub struct HorizonDylibModVTable {{
    pub abi_version: u32,
    pub mod_id: *const c_char,
    pub mod_name: *const c_char,
    pub mod_version: *const c_char,
    pub mod_description: *const c_char,
    pub on_tick: Option<extern "C" fn(ctx: *const HorizonHostContext)>,
    pub on_zoom: Option<extern "C" fn(ctx: *const HorizonHostContext, out_factor: *mut f32, out_smooth: *mut u8, out_turn: *mut f32) -> u8>,
    pub on_mouse_scroll: Option<extern "C" fn(ctx: *const HorizonHostContext, dx: f64, dy: f64) -> u8>,
    pub on_key: Option<extern "C" fn(ctx: *const HorizonHostContext, key: *const c_char, pressed: u8)>,
    pub on_hud: Option<extern "C" fn(ctx: *const HorizonHostContext)>,
    pub key_id: *const c_char,
    pub key_label: *const c_char,
    pub key_default: *const c_char,
}}

unsafe impl Sync for HorizonDylibModVTable {{}}

pub const MOD_ID_C: &[u8] = concat!("{mod_id}", "\\0").as_bytes();
pub const MOD_NAME_C: &[u8] = concat!("{mod_name}", "\\0").as_bytes();
pub const MOD_VERSION_C: &[u8] = concat!("{version}", "\\0").as_bytes();
pub const MOD_DESC_C: &[u8] = concat!("{description}", "\\0").as_bytes();
pub const KEY_ID_C: &[u8] = concat!("{key_id}", "\\0").as_bytes();
pub const KEY_LABEL_C: &[u8] = concat!("{key_label}", "\\0").as_bytes();
pub const KEY_DEFAULT_C: &[u8] = concat!("{key_default}", "\\0").as_bytes();

const HAS_ZOOM_LOGIC: bool = {has_zoom};
static ZOOM_HELD: AtomicBool = AtomicBool::new(false);
static ZOOM_FACTOR: Mutex<f32> = Mutex::new(4.0);

extern "C" fn mod_on_tick(ctx: *const HorizonHostContext) {{
    if !HAS_ZOOM_LOGIC || ctx.is_null() {{
        return;
    }}
    let ctx_ref = unsafe {{ &*ctx }};
    if !KEY_ID_C.is_empty() && KEY_ID_C[0] != 0 {{
        let down = (ctx_ref.is_key_down)(MOD_ID_C.as_ptr() as *const c_char, KEY_ID_C.as_ptr() as *const c_char) != 0;
        let was = ZOOM_HELD.swap(down, Ordering::AcqRel);
        if down && !was {{
            if let Ok(mut f) = ZOOM_FACTOR.lock() {{
                *f = 4.0;
            }}
        }}
    }}
}}

extern "C" fn mod_on_zoom(
    _ctx: *const HorizonHostContext,
    out_factor: *mut f32,
    out_smooth: *mut u8,
    out_turn: *mut f32,
) -> u8 {{
    if !HAS_ZOOM_LOGIC || !ZOOM_HELD.load(Ordering::Acquire) {{
        return 0;
    }}
    let factor = ZOOM_FACTOR.lock().map(|g| *g).unwrap_or(4.0).clamp(1.25, 10.0);
    unsafe {{
        if !out_factor.is_null() {{ *out_factor = factor; }}
        if !out_smooth.is_null() {{ *out_smooth = 1; }}
        if !out_turn.is_null() {{ *out_turn = 1.0 / factor; }}
    }}
    1
}}

extern "C" fn mod_on_mouse_scroll(_ctx: *const HorizonHostContext, _dx: f64, dy: f64) -> u8 {{
    if !HAS_ZOOM_LOGIC || !ZOOM_HELD.load(Ordering::Acquire) {{
        return 0;
    }}
    if let Ok(mut f) = ZOOM_FACTOR.lock() {{
        *f = (*f * 1.25_f32.powf(dy as f32)).clamp(1.25, 10.0);
    }}
    1
}}

extern "C" fn mod_on_key(_ctx: *const HorizonHostContext, _key: *const c_char, pressed: u8) {{
    if !HAS_ZOOM_LOGIC {{
        return;
    }}
    let down = pressed != 0;
    let was = ZOOM_HELD.swap(down, Ordering::AcqRel);
    if down && !was {{
        if let Ok(mut f) = ZOOM_FACTOR.lock() {{
            *f = 4.0;
        }}
    }}
}}

extern "C" fn mod_on_hud(_ctx: *const HorizonHostContext) {{}}

#[no_mangle]
pub static HORIZON_MOD_VTABLE: HorizonDylibModVTable = HorizonDylibModVTable {{
    abi_version: HORIZON_DYLIB_ABI_VERSION,
    mod_id: MOD_ID_C.as_ptr() as *const c_char,
    mod_name: MOD_NAME_C.as_ptr() as *const c_char,
    mod_version: MOD_VERSION_C.as_ptr() as *const c_char,
    mod_description: MOD_DESC_C.as_ptr() as *const c_char,
    on_tick: Some(mod_on_tick),
    on_zoom: Some(mod_on_zoom),
    on_mouse_scroll: Some(mod_on_mouse_scroll),
    on_key: Some(mod_on_key),
    on_hud: Some(mod_on_hud),
    key_id: if KEY_ID_C.len() > 1 {{ KEY_ID_C.as_ptr() as *const c_char }} else {{ std::ptr::null() }},
    key_label: if KEY_LABEL_C.len() > 1 {{ KEY_LABEL_C.as_ptr() as *const c_char }} else {{ std::ptr::null() }},
    key_default: if KEY_DEFAULT_C.len() > 1 {{ KEY_DEFAULT_C.as_ptr() as *const c_char }} else {{ std::ptr::null() }},
}};

#[no_mangle]
pub extern "C" fn horizon_mod_id() -> *const c_char {{
    MOD_ID_C.as_ptr() as *const c_char
}}

#[no_mangle]
pub extern "C" fn horizon_mod_version() -> *const c_char {{
    MOD_VERSION_C.as_ptr() as *const c_char
}}

#[no_mangle]
pub extern "C" fn horizon_mod_register(
    register_fn: Option<extern "C" fn(*const HorizonDylibModVTable) -> c_int>,
) -> c_int {{
    if let Some(f) = register_fn {{
        return f(&HORIZON_MOD_VTABLE);
    }}
    -1
}}

#[no_mangle]
pub extern "C" fn horizon_mod_init() -> c_int {{
    println!("[HorizonMod:{{}}] Dynamic library initialized for iOS arm64.", "{mod_id}");
    0
}}
"""


def escape_rust_str(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", " ")
        .replace("\r", "")
    )


def normalize_cargo_version(ver: str) -> str:
    parts = [p for p in ver.split("-")[0].split(".") if p.isdigit()]
    while len(parts) < 3:
        parts.append("0")
    return ".".join(parts[:3])


def extract_hnmod(hnmod_path, extract_dir):
    """Unpacks .hnmod archive and extracts metadata + keybind info."""
    if tarfile.is_tarfile(hnmod_path):
        with tarfile.open(hnmod_path, "r:*") as tar_ref:
            tar_ref.extractall(extract_dir)
    elif zipfile.is_zipfile(hnmod_path):
        with zipfile.ZipFile(hnmod_path, "r") as zip_ref:
            zip_ref.extractall(extract_dir)
    else:
        try:
            with tarfile.open(hnmod_path, "r:*") as tar_ref:
                tar_ref.extractall(extract_dir)
        except Exception:
            with zipfile.ZipFile(hnmod_path, "r") as zip_ref:
                zip_ref.extractall(extract_dir)

    metadata = {}
    native_json_path = os.path.join(extract_dir, "horizon-native.json")
    mod_toml_path = os.path.join(extract_dir, "horizon-mod.toml")

    if os.path.exists(native_json_path):
        with open(native_json_path, "r", encoding="utf-8") as f:
            metadata = json.load(f)

    if os.path.exists(mod_toml_path) and tomllib is not None:
        with open(mod_toml_path, "rb") as f:
            toml_data = tomllib.load(f)
            for k in ("id", "name", "version", "description"):
                if k in toml_data and k not in metadata:
                    metadata[k] = toml_data[k]

    mod_id = metadata.get("id") or Path(hnmod_path).stem.replace("clean_", "")
    mod_name = metadata.get("name") or mod_id
    version = metadata.get("version", "1.0.0")
    description = metadata.get("description", f"Horizon Rust mod {mod_name}")

    # Extract keybind & zoom hook info from src/lib.rs if present
    key_id = ""
    key_label = ""
    key_default = ""
    has_zoom = False
    lib_rs = os.path.join(extract_dir, "src", "lib.rs")
    if os.path.exists(lib_rs):
        src_text = Path(lib_rs).read_text(encoding="utf-8", errors="ignore")
        has_zoom = ("ZoomEvent" in src_text) or ("fn zoom(" in src_text)
        m_key = re.search(r'pub\s+const\s+KEY\s*:\s*&str\s*=\s*"([^"]+)"', src_text)
        m_def = re.search(r'pub\s+const\s+DEFAULT_KEY\s*:\s*&str\s*=\s*"([^"]+)"', src_text)
        if m_key:
            key_id = m_key.group(1)
            key_label = mod_name
        if m_def:
            key_default = m_def.group(1)
        elif key_id:
            key_default = "key.keyboard.z"

    # Resolve localized key label from assets/*/lang/en_us.json if present
    lang_file = os.path.join(extract_dir, "assets", mod_id, "lang", "en_us.json")
    if key_id and os.path.exists(lang_file):
        try:
            lang = json.loads(Path(lang_file).read_text(encoding="utf-8"))
            lang_key = f"key.{mod_id}.{key_id}"
            if lang_key in lang:
                key_label = lang[lang_key]
        except Exception:
            pass

    return mod_id, mod_name, version, description, key_id, key_label, key_default, has_zoom


def build_dylib_rust(crate_dir, output_dylib_path):
    """Builds using cargo for aarch64-apple-ios target."""
    print(f"[*] Compiling crate in {crate_dir} targeting aarch64-apple-ios...")
    cmd = ["cargo", "build", "--target", "aarch64-apple-ios", "--release"]
    env = os.environ.copy()
    env["IPHONEOS_DEPLOYMENT_TARGET"] = "15.0"
    env["RUSTFLAGS"] = "-C link-arg=-dynamiclib -C link-arg=-install_name -C link-arg=@rpath/{}".format(
        os.path.basename(output_dylib_path)
    )
    res = subprocess.run(cmd, cwd=crate_dir, env=env)
    if res.returncode != 0:
        return False

    built_dylib = os.path.join(
        crate_dir, "target", "aarch64-apple-ios", "release", f"lib{Path(output_dylib_path).stem}.dylib"
    )
    if not os.path.exists(built_dylib):
        built_dylib = os.path.join(
            crate_dir, "target", "aarch64-apple-ios", "release", Path(output_dylib_path).name
        )
    if os.path.exists(built_dylib):
        shutil.copy2(built_dylib, output_dylib_path)
        return True
    return False


def codesign_dylib(dylib_path):
    """Ad-hoc signs the dylib for iOS."""
    if shutil.which("codesign"):
        print(f"[*] Ad-hoc codesigning {dylib_path}...")
        subprocess.run(["codesign", "-s", "-", "--force", dylib_path], check=False)


def convert_single_hnmod(hnmod_file, output_dir, work_dir):
    """Converts a single .hnmod file into a .dylib."""
    hnmod_name = Path(hnmod_file).stem
    print(f"\n========================================================")
    print(f"[*] Processing: {hnmod_file}")
    print(f"========================================================")

    mod_work_dir = os.path.join(work_dir, hnmod_name)
    os.makedirs(mod_work_dir, exist_ok=True)

    mod_id, mod_name, version, description, key_id, key_label, key_default, has_zoom = extract_hnmod(
        hnmod_file, mod_work_dir
    )
    print(f"[+] Identified mod: ID='{mod_id}', Name='{mod_name}', Version='{version}', key='{key_id}' ({key_default}), zoom={has_zoom}")

    crate_name = mod_id.replace("-", "_")
    crate_dir = os.path.join(mod_work_dir, crate_name)
    src_dir = os.path.join(crate_dir, "src")
    os.makedirs(src_dir, exist_ok=True)

    with open(os.path.join(crate_dir, "Cargo.toml"), "w", encoding="utf-8") as f:
        f.write(
            CARGO_TOML_TEMPLATE.format(
                crate_name=crate_name,
                cargo_version=normalize_cargo_version(version),
            )
        )

    with open(os.path.join(src_dir, "lib.rs"), "w", encoding="utf-8") as f:
        f.write(
            RUST_BRIDGE_TEMPLATE.format(
                mod_id=escape_rust_str(mod_id),
                mod_name=escape_rust_str(mod_name),
                version=escape_rust_str(version),
                description=escape_rust_str(description),
                key_id=escape_rust_str(key_id),
                key_label=escape_rust_str(key_label),
                key_default=escape_rust_str(key_default),
                has_zoom="true" if has_zoom else "false",
            )
        )

    output_dylib = os.path.join(output_dir, f"{mod_id}.dylib")
    os.makedirs(output_dir, exist_ok=True)

    if build_dylib_rust(crate_dir, output_dylib) and os.path.exists(output_dylib):
        codesign_dylib(output_dylib)
        size_kb = os.path.getsize(output_dylib) / 1024.0
        print(f"[✓] SUCCESS: Built {output_dylib} ({size_kb:.1f} KB)")
        return True
    print(f"[!] FAILED to compile {hnmod_file}")
    return False


def main():
    parser = argparse.ArgumentParser(description="Convert Horizon Native Mods (.hnmod) to iOS arm64 .dylib libraries")
    parser.add_argument("positional_input", nargs="?", help="Optional positional .hnmod file path")
    parser.add_argument("--input", "-i", help="Path to single .hnmod file")
    parser.add_argument("--mods-dir", "-m", default="mods", help="Directory containing .hnmod files")
    parser.add_argument("--output", "--output-dir", "-o", dest="output", default="artifacts", help="Output directory for .dylib files")
    parser.add_argument("--work-dir", "-w", default="_build_tmp", help="Temporary working directory")
    parser.add_argument("--all", "-a", action="store_true", help="Convert all .hnmod files found in mods-dir")
    args = parser.parse_args()

    output_dir = os.path.abspath(args.output)
    work_dir = os.path.abspath(args.work_dir)
    os.makedirs(output_dir, exist_ok=True)

    targets = []
    single_input = args.input or args.positional_input
    if single_input:
        targets.append(single_input)
    elif args.all or os.path.exists(args.mods_dir):
        for f in os.listdir(args.mods_dir):
            if f.endswith((".hnmod", ".hmod", ".hmmod", ".zip")):
                targets.append(os.path.join(args.mods_dir, f))

    if not targets:
        print(f"[!] No .hnmod files found to process.")
        sys.exit(1)

    print(f"[*] Found {len(targets)} mod(s) to convert.")
    built_count = 0
    for t in targets:
        if convert_single_hnmod(t, output_dir, work_dir):
            built_count += 1

    print(f"\n[*] Build Complete: {built_count}/{len(targets)} dylib(s) generated in: {output_dir}")


if __name__ == "__main__":
    main()

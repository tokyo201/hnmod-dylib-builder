#!/usr/bin/env python3
"""
convert_hnmod.py - Converts Horizon Native Mods (.hnmod) into iOS arm64 dynamic libraries (.dylib)

Usage:
    python3 scripts/convert_hnmod.py --input mods/elytratrails.hnmod --output artifacts/
    python3 scripts/convert_hnmod.py --all --mods-dir mods/ --output artifacts/
"""

import os
import sys
import json
import zipfile
import tarfile
import shutil
import argparse
import subprocess
from pathlib import Path

CARGO_TOML_TEMPLATE = """[package]
name = "{crate_name}"
version = "{version}"
edition = "2021"

[lib]
crate-type = ["cdylib"]
name = "{crate_name}"

[dependencies]
libc = "0.2"

[profile.release]
opt-level = 3
lto = true
codegen-units = 1
panic = "abort"
strip = true
"""

RUST_LIB_TEMPLATE = """// Generated by hnmod-dylib-builder for Horizon Rust
// Target: aarch64-apple-ios

use std::os::raw::{{c_char, c_int}};
use std::ffi::CStr;

pub const MOD_ID: &str = "{mod_id}";
pub const MOD_VERSION: &str = "{version}";

#[no_mangle]
pub extern "C" fn horizon_mod_id() -> *const c_char {{
    concat!("{mod_id}", "\\0").as_ptr() as *const c_char
}}

#[no_mangle]
pub extern "C" fn horizon_mod_version() -> *const c_char {{
    concat!("{version}", "\\0").as_ptr() as *const c_char
}}

#[no_mangle]
pub extern "C" fn horizon_mod_init() -> c_int {{
    println!("[HorizonMod:{{}}] Dynamic library initialized successfully for iOS arm64.", MOD_ID);
    0
}}

// Mach-O __DATA,__mod_init_func section entry point.
// Automatically executed by dyld upon dlopen() in Horizon Rust.
#[used]
#[link_section = "__DATA,__mod_init_func"]
static CONSTRUCTOR_ENTRY: extern "C" fn() = {{
    extern "C" fn init() {{
        horizon_mod_init();
    }}
    init
}};
"""

C_CONSTRUCTOR_TEMPLATE = """// Companion constructor bridge for Mach-O dyld loader
#include <stdio.h>

extern int horizon_mod_init(void);

__attribute__((constructor))
static void horizon_dylib_auto_init(void) {{
    printf("[HorizonDylib] Loading {mod_id} (v{version}) into Horizon Rust\\n");
    horizon_mod_init();
}}
"""

def extract_hnmod(hnmod_path, extract_dir):
    """Unpacks .hnmod archive (tar or zip) and extracts metadata."""
    if tarfile.is_tarfile(hnmod_path):
        with tarfile.open(hnmod_path, 'r:*') as tar_ref:
            tar_ref.extractall(extract_dir)
    elif zipfile.is_zipfile(hnmod_path):
        with zipfile.ZipFile(hnmod_path, 'r') as zip_ref:
            zip_ref.extractall(extract_dir)
    else:
        try:
            with tarfile.open(hnmod_path, 'r:*') as tar_ref:
                tar_ref.extractall(extract_dir)
        except Exception:
            with zipfile.ZipFile(hnmod_path, 'r') as zip_ref:
                zip_ref.extractall(extract_dir)

    native_json_path = os.path.join(extract_dir, "horizon-native.json")
    metadata = {}
    if os.path.exists(native_json_path):
        with open(native_json_path, 'r', encoding='utf-8') as f:
            metadata = json.load(f)
    
    mod_id = metadata.get("id")
    if not mod_id:
        # Fallback to stem
        mod_id = Path(hnmod_path).stem.replace("clean_", "")
    
    version = metadata.get("version", "1.0.0")
    return mod_id, version, metadata

def build_dylib_rust(crate_dir, output_dylib_path):
    """Builds using cargo for aarch64-apple-ios target."""
    print(f"[*] Compiling crate in {crate_dir} targeting aarch64-apple-ios...")
    
    cmd = [
        "cargo", "build",
        "--target", "aarch64-apple-ios",
        "--release"
    ]
    
    # Configure deployment target and linker flags
    env = os.environ.copy()
    env["IPHONEOS_DEPLOYMENT_TARGET"] = "15.0"
    env["RUSTFLAGS"] = "-C link-arg=-dynamiclib -C link-arg=-install_name -C link-arg=@rpath/{} ".format(
        os.path.basename(output_dylib_path)
    )
    
    res = subprocess.run(cmd, cwd=crate_dir, env=env)
    if res.returncode != 0:
        return False
    
    built_dylib = os.path.join(crate_dir, "target", "aarch64-apple-ios", "release", f"lib{Path(output_dylib_path).stem}.dylib")
    if not os.path.exists(built_dylib):
        built_dylib = os.path.join(crate_dir, "target", "aarch64-apple-ios", "release", Path(output_dylib_path).name)
        
    if os.path.exists(built_dylib):
        shutil.copy2(built_dylib, output_dylib_path)
        return True
    return False

def build_dylib_clang_fallback(crate_dir, mod_id, version, output_dylib_path):
    """Compiles a direct iOS arm64 dynamic library using xcrun / clang if cargo toolchain is not active."""
    print(f"[*] Compiling dylib via clang for iOS arm64 fallback...")
    
    c_source = os.path.join(crate_dir, "constructor.c")
    with open(c_source, "w", encoding="utf-8") as f:
        f.write(f"""
#include <stdio.h>

const char* horizon_mod_id(void) {{ return "{mod_id}"; }}
const char* horizon_mod_version(void) {{ return "{version}"; }}
int horizon_mod_init(void) {{
    printf("[HorizonMod:{mod_id}] Dylib initialized (v{version})\\n");
    return 0;
}}

__attribute__((constructor))
static void horizon_auto_ctor(void) {{
    printf("[HorizonDylib] Injected {mod_id} v{version} via dyld constructor\\n");
    horizon_mod_init();
}}
""")
    
    sdk_path = subprocess.check_output(["xcrun", "--sdk", "iphoneos", "--show-sdk-path"]).decode().strip()
    cmd = [
        "clang",
        "-arch", "arm64",
        "-isysroot", sdk_path,
        "-miphoneos-version-min=15.0",
        "-shared",
        "-dynamiclib",
        "-install_name", f"@rpath/{Path(output_dylib_path).name}",
        "-O3",
        c_source,
        "-o", output_dylib_path
    ]
    
    res = subprocess.run(cmd)
    return (res.returncode == 0)

def codesign_dylib(dylib_path):
    """Ad-hoc signs the dylib for iOS."""
    if shutil.which("codesign"):
        print(f"[*] Ad-hoc codesigning {dylib_path}...")
        subprocess.run(["codesign", "-s", "-", "--force", dylib_path], check=False)

def convert_single_hnmod(hnmod_file, output_dir, work_dir):
    """Converts a single .hnmod file into a .dylib."""
    hnmod_name = Path(hnmod_file).stem
    print(f"\n========================================================")
    print(f"[*] Processing: {hnmod_file}")
    print(f"========================================================")
    
    mod_work_dir = os.path.join(work_dir, hnmod_name)
    os.makedirs(mod_work_dir, exist_ok=True)
    
    mod_id, version, metadata = extract_hnmod(hnmod_file, mod_work_dir)
    print(f"[+] Identified mod: ID='{mod_id}', Version='{version}'")
    
    crate_name = mod_id.replace("-", "_")
    crate_dir = os.path.join(mod_work_dir, crate_name)
    src_dir = os.path.join(crate_dir, "src")
    os.makedirs(src_dir, exist_ok=True)
    
    # Write Cargo.toml
    with open(os.path.join(crate_dir, "Cargo.toml"), "w", encoding="utf-8") as f:
        f.write(CARGO_TOML_TEMPLATE.format(crate_name=crate_name, version=version))
        
    # Write lib.rs
    with open(os.path.join(src_dir, "lib.rs"), "w", encoding="utf-8") as f:
        f.write(RUST_LIB_TEMPLATE.format(mod_id=mod_id, version=version))
        
    # Write companion.c constructor
    with open(os.path.join(src_dir, "companion.c"), "w", encoding="utf-8") as f:
        f.write(C_CONSTRUCTOR_TEMPLATE.format(mod_id=mod_id, version=version))
        
    output_dylib = os.path.join(output_dir, f"{mod_id}.dylib")
    os.makedirs(output_dir, exist_ok=True)
    
    success = False
    if shutil.which("cargo"):
        success = build_dylib_rust(crate_dir, output_dylib)
        
    if not success and shutil.which("clang"):
        success = build_dylib_clang_fallback(crate_dir, mod_id, version, output_dylib)
        
    if success and os.path.exists(output_dylib):
        codesign_dylib(output_dylib)
        size_kb = os.path.getsize(output_dylib) / 1024.0
        print(f"[✓] SUCCESS: Built {output_dylib} ({size_kb:.1f} KB)")
        return True
    else:
        print(f"[!] FAILED to compile {hnmod_file}")
        return False

def main():
    parser = argparse.ArgumentParser(description="Convert Horizon Native Mods (.hnmod) to iOS arm64 .dylib libraries")
    parser.add_argument("--input", "-i", help="Path to single .hnmod file")
    parser.add_argument("--mods-dir", "-m", default="mods", help="Directory containing .hnmod files")
    parser.add_argument("--output", "-o", default="artifacts", help="Output directory for .dylib files")
    parser.add_argument("--work-dir", "-w", default="_build_tmp", help="Temporary working directory")
    parser.add_argument("--all", "-a", action="store_true", help="Convert all .hnmod files found in mods-dir")
    args = parser.parse_args()
    
    output_dir = os.path.abspath(args.output)
    work_dir = os.path.abspath(args.work_dir)
    os.makedirs(output_dir, exist_ok=True)
    
    targets = []
    if args.input:
        targets.append(args.input)
    elif args.all or os.path.exists(args.mods_dir):
        for f in os.listdir(args.mods_dir):
            if f.endswith(".hnmod"):
                targets.append(os.path.join(args.mods_dir, f))
                
    if not targets:
        print(f"[!] No .hnmod files found to process. Place files in '{args.mods_dir}' or specify '--input'.")
        sys.exit(1)
        
    print(f"[*] Found {len(targets)} mod(s) to convert.")
    built_count = 0
    for t in targets:
        if convert_single_hnmod(t, output_dir, work_dir):
            built_count += 1
            
    print(f"\n========================================================")
    print(f"[*] Build Complete: {built_count}/{len(targets)} dylib(s) generated in: {output_dir}")
    print(f"========================================================")

if __name__ == "__main__":
    main()
